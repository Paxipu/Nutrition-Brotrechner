"""Erzeugt die mitgelieferte Startdatenbank ``data/seed/ingredients.json``.

Diese Datei ist die *Quelle der Wahrheit* für die ausgelieferten Zutatenwerte.
Sie ist bewusst ein Generator und keine handgepflegte JSON-Datei, weil damit

* jeder Wert eine nachvollziehbare Quelle bekommt,
* der Brennwert nicht abgetippt, sondern nach Anhang XIV der VO (EU)
  Nr. 1169/2011 aus den Nährstoffen **berechnet** wird, und
* die Datenbank jederzeit reproduzierbar neu erzeugt werden kann.

Aufruf::

    python tools/build_seed_database.py

Konventionen der Tabelle unten
------------------------------
``carbs``
    Kohlenhydrate nach EU-Konvention, also **ohne** Ballaststoffe. Bei Werten
    aus der USDA-Datenbank wurden die Ballaststoffe vorher abgezogen; genau
    dieses Detail war die Ursache mehrerer Fehler in der Altdatenbank.
``energy``
    Nur setzen, wenn ein Etikettwert bewusst dem berechneten vorgezogen wird.
    Sonst wird gerechnet.
``water``
    Durchweg fachlich abgeleitet (Handelsüblichkeit, Massenbilanz), weil dieser
    Wert auf keinem Etikett steht.
"""

