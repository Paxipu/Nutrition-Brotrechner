def build() -> list[Ingredient]:
    """Baut die Zutatenliste aus der Tabelle."""
    stand = date.fromisoformat(PRICE_DATE)
    ingredients: list[Ingredient] = []
    for name, manufacturer, category, is_flour, nutrients, price, size, psrc, nsrc, note in TABLE:
        ingredients.append(
            Ingredient(
                name=name,
                manufacturer=manufacturer,
                category=category,
                nutrients=nutrients,
                is_flour=is_flour,
                package_price=price,
                package_size_g=size,
                price_source=psrc,
                price_updated=stand,
                nutrition_source=Source.REFERENCE,
                water_source=Source.ESTIMATED,
                notes=" ".join(filter(None, [note, f"Nährwertquelle: {nsrc}."])),
            )
        )
    return ingredients


def main() -> int:
    """Erzeugt die Datei und prüft sie sofort; Fehler brechen ab."""
    ingredients = build()

    keys = [i.key for i in ingredients]
    duplicates = {k for k in keys if keys.count(k) > 1}
    if duplicates:
        print(f"FEHLER: doppelte Schlüssel: {sorted(duplicates)}", file=sys.stderr)
        return 1

    findings = validate_database(ingredients)
    errors = [f for f in findings if f.severity is Severity.ERROR]
    warnings = [f for f in findings if f.severity is Severity.WARNING]

    for finding in errors + warnings:
        print(f"  {finding}", file=sys.stderr)

    if errors:
        print(f"FEHLER: {len(errors)} Bilanzfehler in der Startdatenbank", file=sys.stderr)
        return 1

    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "generator": f"tools/build_seed_database.py (brotrechner {__version__})",
        "price_date": PRICE_DATE,
        "ingredients": [
            i.to_dict() for i in sorted(ingredients, key=lambda x: x.display_name.casefold())
        ],
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"{len(ingredients)} Zutaten geschrieben nach {OUTPUT}")
    print(f"  {len(warnings)} Warnungen, 0 Fehler")
    priced = sum(1 for i in ingredients if i.has_price)
    print(f"  {priced}/{len(ingredients)} mit Preis")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
