def n(
    fat: float,
    sat: float,
    carbs: float,
    sugar: float,
    protein: float,
    fiber: float,
    salt: float,
    water: float,
    *,
    energy: float | None = None,
) -> Nutrients:
    """Baut einen Nährwertvektor; der Brennwert wird berechnet, wenn nicht gesetzt."""
    base = Nutrients(
        fat=fat,
        saturated_fat=sat,
        carbs=carbs,
        sugar=sugar,
        protein=protein,
        fiber=fiber,
        salt=salt,
        water=water,
    )
    kcal = energy if energy is not None else round(energy_from_macros(base))
    return base.with_values(energy_kcal=kcal)


